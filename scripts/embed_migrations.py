#!/usr/bin/env python3
"""Compile migrations/*.sql into the control server binary.

The migrations are read from disk by this script at BUILD time and emitted as C++
string literals, so a deployed control server needs no .sql files next to it. Only
`dbbase/base.db` stays a runtime file, and only for databases that do not exist
yet.

Writes only when the output would change, so `make` does not rebuild the
translation unit after every invocation.

Usage:
    python3 scripts/embed_migrations.py --dir migrations --out <file.cpp>
"""

import argparse
import glob
import os
import sys


def load(migrations_dir):
    entries = []
    seen = {}
    for path in sorted(glob.glob(os.path.join(migrations_dir, "*.sql"))):
        name = os.path.basename(path)
        digits = ""
        for ch in name:
            if not ch.isdigit():
                break
            digits += ch
        if not digits:
            sys.exit(f"error: {name} has no numeric version prefix (NNNN-slug.sql)")
        version = int(digits)
        if version in seen:
            sys.exit(f"error: version {version} is claimed by both {seen[version]} and {name}")
        seen[version] = name
        with open(path, "r", encoding="utf-8") as f:
            sql = f.read()
        if ')SQL"' in sql:
            sys.exit(f"error: {name} contains the raw-string terminator )SQL\"")
        entries.append((version, name, sql))
    entries.sort(key=lambda e: e[0])
    return entries


def render(entries):
    out = []
    out.append("// GENERATED by scripts/embed_migrations.py -- do not edit.")
    out.append("// Contents of migrations/*.sql, compiled in so a deployed control server")
    out.append("// needs no .sql files beside it. Regenerated by make.")
    out.append('#include "src/ControlServer/Database/EmbeddedMigrations.hpp"')
    out.append("")
    out.append("namespace EmbeddedMigrations {")
    out.append("")
    if not entries:
        out.append("const Migration kMigrations[] = {{0, \"\", \"\"}};")
        out.append("const int kCount = 0;")
    else:
        out.append("const Migration kMigrations[] = {")
        for version, name, sql in entries:
            out.append("    {%d, %s," % (version, cstr(name)))
            out.append('        R"SQL(%s)SQL"},' % sql)
        out.append("};")
        out.append("const int kCount = %d;" % len(entries))
    out.append("")
    out.append("}  // namespace EmbeddedMigrations")
    out.append("")
    return "\n".join(out)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="migrations")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    entries = load(args.dir)
    text = render(entries)

    existing = None
    if os.path.exists(args.out):
        with open(args.out, "r", encoding="utf-8") as f:
            existing = f.read()
    if existing == text:
        return 0   # unchanged: leave the mtime alone so make skips the rebuild

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"embed_migrations: {len(entries)} migration(s) -> {args.out}"
          + (f" (latest v{entries[-1][0]})" if entries else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
