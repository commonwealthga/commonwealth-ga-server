#!/usr/bin/env python3
"""Generate src/Shared/BuildVersion.gen.hpp from git.

The node agent version used to be a hand-maintained constant ("0.1.0"), which is
one more thing to forget to bump. It now comes from git at build time:

    0.1.58-1-ge5c42b4-dirty
    │      │ │  └── working tree had uncommitted changes
    │      │ └───── abbreviated commit
    │      └────── commits since that tag
    └───────────── nearest tag

That works locally with no network and no GitHub release: a tag when one exists,
the commit always. A build from a tarball with no .git degrades to "unknown"
rather than failing.

Writes only when the content changes, so an unchanged tree does not rebuild the
files that include the header.

Tag timing: `git describe` uses the nearest tag *reachable from HEAD*, so a
binary built before you tag reports "0.1.58-5-gabc1234" rather than "0.1.59".
That is still exact (the commit is in the string), but if you want the artifact to
carry the release number, either tag before building or stamp it:

    GA_BUILD_VERSION=0.1.59 make control-server-linux
    GA_BUILD_VERSION=0.1.59 make out/version.dll

The override is used verbatim; git's dirty flag is still reported honestly.

Usage:
    python3 scripts/gen_version.py --out src/Shared/BuildVersion.gen.hpp
"""

import argparse
import os
import subprocess
import sys


def git(*args: str) -> str:
    try:
        out = subprocess.run(
            ["git", *args],
            capture_output=True,
            text=True,
            timeout=10,
            cwd=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    if out.returncode != 0:
        return ""
    return out.stdout.strip()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    describe = git("describe", "--tags", "--long", "--dirty", "--always")
    commit = git("rev-parse", "HEAD")
    # The "-dirty" marker is kept in kDescribe on purpose: a build from a modified
    # tree is not the build the tag names, and that should be visible wherever the
    # version is logged or compared. BuildVersion::Parse ignores the suffix.
    dirty = describe.endswith("-dirty")

    # Explicit stamp, for building a release artifact before the tag exists.
    override = (os.environ.get("GA_BUILD_VERSION") or "").strip()
    if override:
        print(f"gen_version: version overridden to {override} "
              f"(git says {describe or 'nothing'})", file=sys.stderr)
        describe = override

    if not describe:
        # No git, or not a repository. Say so loudly once and keep going: a build
        # without git is legitimate (tarball, CI export), an unbuildable tree is not.
        print("gen_version: no git metadata -- reporting version 'unknown'", file=sys.stderr)
        describe = "unknown"
        commit = "unknown"
        dirty = False

    head = "// GENERATED by scripts/gen_version.py -- do not edit."
    body = f"""{head}
// Derived from `git describe --tags --long --dirty` at build time. Rebuild to
// refresh; there is no version number to maintain by hand.
#include <cstdint>

namespace BuildVersion {{

// The full description: nearest tag, commits since it, commit, dirty marker.
constexpr const char* kDescribe = "{describe}";

// Full commit the binary was built from ("unknown" without git metadata).
constexpr const char* kCommit = "{commit}";

// Worth surfacing on its own: two nodes on the same tag are not necessarily on
// the same code.
constexpr bool kDirty = {"true" if dirty else "false"};

}}  // namespace BuildVersion
"""
    text = body.replace("\n", "\n")

    existing = None
    if os.path.exists(args.out):
        with open(args.out, "r", encoding="utf-8") as f:
            existing = f.read()
    if existing == text:
        return 0

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"gen_version: {describe}" + (" (dirty)" if dirty else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
